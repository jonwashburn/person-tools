"""Build the runner's generated parts from canon/ (never type a fact by hand).

python3 code/runner/build.py            -> code/runner/lib/hosts.js, code/runner/public/_build.txt, code/site/human/
python3 code/runner/build.py --local DIR -> also a copy of the site page for a local check in DIR (adds 127.0.0.1:8783)
"""
import hashlib, html, json, os, re, shutil, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.abspath(os.path.join(HERE, "..", ".."))
CANON = os.path.join(WORK, "canon")
names = json.load(open(os.path.join(CANON, "names.json")))
canon = json.load(open(os.path.join(CANON, "canon.json")))
promise = json.load(open(os.path.join(CANON, "promise.json")))
# every price number comes from trust's money/price.json 'public' block (canon/canon.json offer.price says so)
PRICE = json.load(open(os.path.join(WORK, canon["offer"]["price"].get("source_file", "money/price.json"))))["public"]


FIRST_CALL_ON = False   # the front page's first-call paragraph (REACH 10:34); held by the CEO at 11:00 AM CT 15 Nov

def fill(s):
    return (s.replace("{network}", names["network"]).replace("{standard}", names["standard"]).replace("{tool}", names["tool"])
             .replace("{domain}", names["domain"]).replace("{wire_prefix}", names["wire_prefix"]))


H, F = names["hosts"], names["fallback_hosts"]
SHOWN = H if names.get("zone_active") else F
hosts = {"primary": {"site": [H["site"], H["www"]], "api": H["api"], "run": H["run"]},
         "fallback": {"site": [F["site"]], "api": F["api"], "run": F["run"]}}

# 1. the runner's server side: which pages may embed the person's page (the front page rings the visitor)
site_origins = ["https://" + h for h in hosts["primary"]["site"] + hosts["fallback"]["site"]]
open(os.path.join(HERE, "lib", "hosts.js"), "w").write(
    "// Generated by code/runner/build.py from canon/names.json. Do not edit.\n"
    f"export const SITE_ORIGINS = {json.dumps(site_origins)};\nexport const NETWORK = {json.dumps(names['network'])};\n")
# the runner's own home page, from canon
open(os.path.join(HERE, "public", "index.html"), "w").write(open(os.path.join(HERE, "site_src", "run_index.html")).read()
    .replace("{{network}}", html.escape(names["network"])).replace("{{network_upper}}", html.escape(names["network"].upper())))
# the runner page posts screen changes to these origins only
open(os.path.join(HERE, "public", "hosts.js"), "w").write(
    "/* Generated by code/runner/build.py from canon/names.json. */\nwindow.PT_SITE_ORIGINS = " + json.dumps(site_origins) + ";\nwindow.PT_NETWORK = " + json.dumps(names["network"]) + ";\n")

# 1b. the tester notice, rendered verbatim by the join page (legal/tester_notice.json, trust)
# trust writes the service's name as {network}; it is filled from canon/names.json here (a rename is one edit)
def _fill_network(o):
    if isinstance(o, str): return re.sub(r"\s*\(hc-[a-z]+\)|hc-[a-z]+;\s*", "", o.replace("{network}", names["network"]))   # and no lane names
    if isinstance(o, list): return [_fill_network(x) for x in o]
    if isinstance(o, dict): return {k: _fill_network(v) for k, v in o.items()}
    return o
_tn = _fill_network(json.load(open(os.path.join(WORK, "legal", "tester_notice.json"))))
assert "{network}" not in json.dumps(_tn), "an unfilled {network} in the tester notice"
json.dump(_tn, open(os.path.join(HERE, "public", "tester_notice.json"), "w"), indent=1, ensure_ascii=False)
open(os.path.join(HERE, "lib", "notice_id.js"), "w").write("// Generated by code/runner/build.py from legal/tester_notice.json. Do not edit.\nexport const NOTICE_ID = " + json.dumps(_tn.get("id", "")) + ";\n")
# 1b'. the notice for joining a principal's own panel (policy/OWN_PANELS.md rule 3; legal/tester_notice_own.json, trust): {network}
# is filled here; {principal} stays, and the join page fills it with the name the asker gave (shown as not checked)
_tno = os.path.join(WORK, "legal", "tester_notice_own.json")
if os.path.exists(_tno):
    _own = _fill_network(json.load(open(_tno)))
    assert "{network}" not in json.dumps(_own), "an unfilled {network} in the own-panel notice"
    json.dump(_own, open(os.path.join(HERE, "public", "tester_notice_own.json"), "w"), indent=1, ensure_ascii=False)

# 1c. the recording release: trust's legal/recording_release.json is the one record (since 14 Nov 2:23 AM CT); copied as is.
#     The older path below (parsing legal/RECORDING_RELEASE.md) runs only if that file is missing.
_rr_json = os.path.join(WORK, "legal", "recording_release.json")
_use_rr_json = os.path.exists(_rr_json)
import re as _re
_rr = open(os.path.join(WORK, "legal", "RECORDING_RELEASE.md")).read()
_items = []
for _m in _re.finditer(r"^(\d+)\. \*\*(.+?)\*\* (.+?)(?=^\s*\*Why:|^\d+\. |^\[|\Z)", _rr, _re.S | _re.M):
    _t = " ".join(_m.group(3).split())
    if _t.startswith("_(") and "or none:" in _t:   # trust's either/or for the transcriber: none is named, so its 'none' branch
        _rest = _t.split("or none:", 1)[1].strip().rstrip(")_").strip()
        _t = "None is named yet. " + _rest[0].upper() + _rest[1:]
    _items.append({"n": int(_m.group(1)), "label": _m.group(2).rstrip("."), "text": _t})
_accept = _re.search(r"^\[ (.+?) \]\s+\[ (.+?) \]", _rr, _re.M)
_rid = _re.search(r"Release id: `([^`]+)`", _rr)
_lead = _re.search(r"^\*\*Before you speak an answer, please read this\.\*\* (.+)$", _rr, _re.M)
if _use_rr_json:
    json.dump(_fill_network(json.load(open(_rr_json))), open(os.path.join(HERE, "public", "recording_release.json"), "w"), indent=1, ensure_ascii=False)
else:
  json.dump({"id": _rid.group(1) if _rid else "voice-release-1", "title": "Before you speak an answer, please read this.",
           "lede": _lead.group(1).strip() if _lead else "You can always type instead.", "items": _items,
           "accept": _accept.group(1) if _accept else "I agree to record my spoken answer on this call",
           "decline": _accept.group(2) if _accept else "Type instead",
           "status": "draft for counsel, not in force: shown on simulated and team-test calls only until the voice rules are live",
           "source": "legal/RECORDING_RELEASE.md"}, open(os.path.join(HERE, "public", "recording_release.json"), "w"), indent=1)

# 2. the front page for askpeople-site, handed to market as code/site/human/
src = os.path.join(HERE, "site_src")
out = os.path.join(WORK, "code", "site", "human")


def build_site(out, extra_hosts=()):
    os.makedirs(os.path.join(out, "h", "fonts"), exist_ok=True)
    css = open(os.path.join(src, "front.css")).read()
    evidence = {k: v for k, v in canon["evidence_levels"].items() if k in ("said", "attended", "voiced")}
    # the cost a human who sets an agent's budget needs to see: trust's public worked example closest to the demo call
    _ex = [e for e in json.load(open(os.path.join(WORK, "money", "price.json"))).get("examples", []) if e.get("public")]
    _ex = next((e for e in _ex if "two minutes" in e.get("case", "")), _ex[0] if _ex else None)
    js = (open(os.path.join(src, "front.js")).read().replace("{{evidence_json}}", json.dumps(evidence))
          .replace("{{price_example_json}}", json.dumps({"example": _ex, "status": canon["offer"]["price"]["plain_status"], "pool_pct": PRICE["pool_fee"]["pct"], "floor": PRICE["pay_floor"]["usd_per_hour"].split(".")[0]})))
    v = hashlib.sha256((css + js).encode()).hexdigest()[:10]
    apis = ["https://" + hosts["primary"]["api"], "https://" + hosts["fallback"]["api"]] + list(extra_hosts)
    runs = ["https://" + hosts["primary"]["run"], "https://" + hosts["fallback"]["run"]] + list(extra_hosts)
    csp = ("default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; "
           f"connect-src 'self' {' '.join(apis)}; frame-src {' '.join(runs)}; object-src 'none'; base-uri 'none'; form-action 'self'")
    call = {"_tool": names["tool"], "ask": "Listen once, to the end. Then say what you felt, in your own words.", "kind": "listen",
            "content": "m_sample_melody30", "people": 1, "pool": "self",
            "answer_fields": {"felt": {"type": "text", "label": "What did you feel?"},
                              "would_play_again": {"type": "boolean", "label": "Would you play it again?"}}}
    price = canon["offer"]["price"]
    rf, floor, dflt = PRICE["router_fee"], PRICE["pay_floor"], PRICE["pay_default"]
    # which promise lines are really checked after every release: canon/promise.json 'baseline_rule' (all listed baseline
    # lines PASS in the latest api baseline)
    passed = set()
    import glob
    gd = os.environ.get("GOLIVE_DIR")   # the deploy records, when this build runs beside them
    cands = [f for f in glob.glob(os.path.join(os.path.expanduser(gd), "askpeople-*", "baseline*.txt")) if os.path.getsize(f) > 200] if gd else []
    bl = max(cands, key=os.path.getmtime) if cands else None   # the newest complete baseline run (a running one is empty)
    if bl:
        for ln in open(bl):
            if ln.startswith("PASS "):
                passed.add(ln[5:].split(":")[0].strip())
    def checked(l):
        names = l.get("baseline_lines") or []
        return bool(names) and all(any(p.startswith(n) for p in passed) for n in names)
    # one record: if market publishes the status (canon/out/promise_status.json: {"checked": ["P1", ...]}), it wins
    ps_file = os.path.join(CANON, "out", "promise_status.json")
    if os.path.exists(ps_file):
        _ids = set(json.load(open(ps_file)).get("checked", []))
        checked = lambda l: l["id"] in _ids
        bl = ps_file
    n_checked = sum(1 for l in promise["lines"] if checked(l))
    lines = "".join(f"<li>{html.escape(fill(l['text']))}" + ('<span class="chk">CHECKED AFTER EVERY RELEASE</span>' if checked(l) else "") + "</li>" for l in promise["lines"])
    words = ["None", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten", "Eleven", "Twelve"]
    print("promise checks from", bl, "->", n_checked, "of", len(promise["lines"]), file=sys.stderr)
    if n_checked == 0:
        promise_h = "Twelve lines. Their checks are being built; none passes after every release yet."
    elif n_checked < len(promise["lines"]):
        promise_h = f"Twelve lines. {words[n_checked]} of them {'is' if n_checked == 1 else 'are'} checked after every release today, marked below."
    else:
        promise_h = "Twelve lines. Each is checked after every release."
    page = open(os.path.join(src, "front.html")).read()
    rep = {
        "{{csp}}": csp, "{{v}}": v, "{{network}}": html.escape(names["network"]), "{{network_upper}}": html.escape(names["network"].upper()),
        "{{tool}}": html.escape(names["tool"]), "{{one_sentence}}": html.escape(fill(canon["identity"]["one_sentence"])),
        "{{status_plain}}": html.escape(fill(canon["status"]["plain"])),
        # REACH 10:34 AM CT 15 Nov (OWNER_market_4): the first real call, from the canon; its outcome is read live from /v1/proof
        # HOLD (the CEO 11:00 AM CT, OWNER_all_9 item 7): off until the owner has settled the public repository; FIRST_CALL_ON = True brings it back.
        # The outcome is the canon's third-person line (REACH 11:01), shown once /v1/proof has the call's outcome; never the raw line
        "{{first_call_section}}": "" if not FIRST_CALL_ON else (lambda fc: ('<section class="first-call" aria-labelledby="fc-h"><h2 id="fc-h">' + html.escape(fill(fc.get("title") or "")) + '</h2><p>'
            + html.escape(fill(fc.get("text") or "")) + '</p><p class="fc-outcome" hidden data-call="' + html.escape(fc.get("call_id") or "", quote=True) + '"><strong>' + html.escape(fill(fc.get("outcome_lead") or "")) + '</strong> <span id="fc-outcome">' + html.escape(fill(fc.get("outcome") or "")) + '</span></p>'
            + '<p><a href="/proof">The record</a></p></section>') if fc.get("text") else "")((canon.get("proof") or {}).get("first_call") or {}),
        # first letter up only: str.capitalize() lowercased the rest and printed "the ahoy protocol" (chief, 12:57)
        "{{status_names}}": html.escape((lambda t: t[:1].upper() + t[1:])(fill(canon["status"]["names"]))),
        "{{hosts_json}}": json.dumps(hosts), "{{call_json}}": json.dumps(call), "{{promise_lines}}": lines, "{{promise_h}}": html.escape(promise_h),
        # the addresses a visitor reads: the person.tools ones once the canon says the zone is active, the pages.dev ones before
        "{{mcp_fallback}}": html.escape("https://" + SHOWN["api"] + "/mcp"),
        "{{spec_fallback}}": html.escape("https://" + SHOWN["spec"] + "/"),
        "{{api_fallback}}": html.escape(SHOWN["api"]),
        "{{router_fee_pct}}": str(rf["pct"]), "{{router_fee_min}}": rf["min_usd_per_call"],
        "{{floor}}": floor["usd_per_hour"].replace(".00", ""), "{{min_call}}": dflt["min_per_person_usd"].replace(".00", ""),
        "{{price_status}}": html.escape(price["plain_status"]),
        # the price cell keeps the canon's first sentence; its test-money sentence is the status line's, said near the top and in the footer
        "{{price_status_short}}": html.escape(price["plain_status"].split(". ")[0].rstrip(".") + "."),
        "{{term_over_cap}}": html.escape(fill(canon["offer"]["terms"]["over_cap"])),
        "{{term_max_total}}": html.escape(fill(canon["offer"]["terms"]["max_total"])),
        "{{term_what_you_pay}}": html.escape(fill(canon["offer"]["terms"]["what_you_pay"])),
        "{{term_overrun}}": html.escape(fill(canon["offer"]["terms"]["overrun"])), "{{term_hold}}": html.escape(fill(canon["offer"]["terms"]["hold"])),
    }
    for k, val in rep.items():
        page = page.replace(k, val)
    left = [p for p in page.split("{{")[1:]]
    if left:
        sys.exit("build: unfilled placeholder {{" + left[0][:30])
    open(os.path.join(out, "index.html"), "w").write(page)
    # the people's page (P5)
    rep.update({
        "{{real_calls}}": html.escape(fill(canon["status"]["real_calls"])),
        "{{promise_also}}": html.escape(" ".join(fill(x) for x in promise.get("also", [])[:1])),
        "{{floor_basis}}": html.escape(floor["basis"][0].upper() + floor["basis"][1:]),
        "{{stop_pay}}": html.escape(PRICE["stop_pay"]), "{{acceptance}}": html.escape(PRICE["acceptance"]),
        # trust's words for the person called (money/price.json for_people), rendered verbatim on /people/
        **{"{{fp_" + k + "}}": html.escape(v) for k, v in json.load(open(os.path.join(WORK, "money", "price.json"))).get("for_people", {}).items() if isinstance(v, str)},
        "{{unpaid_calls}}": html.escape(PRICE["unpaid_calls"]),
    })
    pp = open(os.path.join(src, "people.html")).read()
    for k, val in rep.items():
        pp = pp.replace(k, val)
    if "{{" in pp:
        sys.exit("build: people page has an unfilled placeholder " + pp[pp.index("{{"):pp.index("{{") + 30])
    os.makedirs(os.path.join(out, "people"), exist_ok=True)
    open(os.path.join(out, "people", "index.html"), "w").write(pp)
    open(os.path.join(out, "h", "people.js"), "w").write(open(os.path.join(src, "people.js")).read())
    open(os.path.join(out, "h", "front.css"), "w").write(css)
    open(os.path.join(out, "h", "front.js"), "w").write(js)
    for f in ("inter-var.woff2", "jbmono-400.woff2", "jbmono-700.woff2"):
        shutil.copyfile(os.path.join(HERE, "public", "fonts", f), os.path.join(out, "h", "fonts", f))
    return v


v = build_site(out)
open(os.path.join(HERE, "public", "_build.txt"), "w").write(time.strftime("%Y%m%dT%H%M%SZ", time.gmtime()) + "\n")
print(json.dumps({"site_human": out, "v": v, "site_origins": site_origins}))
if "--local" in sys.argv:
    d = sys.argv[sys.argv.index("--local") + 1]
    build_site(d, extra_hosts=("http://127.0.0.1:8783",))
    print("local copy:", d)
