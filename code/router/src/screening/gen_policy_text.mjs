// Writes policy_text.js from policy/POLICY.md (the one record): the published sections a model read applies.
// Run after any change to POLICY.md: node code/router/src/screening/gen_policy_text.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const pol = readFileSync(join(here, "../../../../policy/POLICY.md"), "utf8");
let t = pol.slice(pol.indexOf("## The one rule behind the rest"), pol.indexOf("## 4. Allowed"));
t = t.replace(/\s*\(`[^`]*\.md`[^)]*\)/g, "").replace(/\{network\}/g, "the service");
writeFileSync(join(here, "policy_text.js"), `// Generated by gen_policy_text.mjs from policy/POLICY.md. Do not edit by hand.\nexport const POLICY_TEXT = ${JSON.stringify(t)};\n`);
console.log("policy_text.js:", t.length, "characters");
